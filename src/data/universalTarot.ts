const buildSuit = (suit: Suit, specs: MinorSpec[]): CardData[] =>
  specs.map(([number, astro, keywords, summary, notes]) => {
    const info = SUIT_INFO[suit];
    return {
      key: `${info.prefix}${RANK_KEY[number]}`,
      name: `${RANK_EN[number]} of ${info.en}`,
      nameKo: `${info.nameKo} ${RANK_KO[number]}`,
      type: 'minor',
      suit,
      number,
      astro,
      element: info.element,
      keywords,
      summary,
      notes,
    };
  });

